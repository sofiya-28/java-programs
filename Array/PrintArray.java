package Array;

public class PrintArray {
    public static void main(String[] args){
        int[] arr ={10,20,30,40,50};
        for(int i=0;i<=arr.length-1;i++){
            System.out.print(arr[i]+" ");
        }
        // print length of array.
        System.out.println(arr.length);

    }
    
    
}
